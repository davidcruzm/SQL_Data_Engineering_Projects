/*
THIS IS CALLED CTAS, OR CREATE TABLE AS SELECT, 
IN THIS QUERY I CREATED THE TABLE job_postings_flat BASED ON TWO TABLES, 
job_postings_fact, and company_dim
*/
CREATE TABLE IF NOT EXISTS staging.job_postings_flat AS
SELECT
    jpf.job_id,
    jpf.job_title_short,
    jpf.job_title,
    jpf.job_location,
    jpf.job_via,
    jpf.job_schedule_type,
    jpf.job_work_from_home,
    jpf.search_location,
    jpf.job_posted_date,
    jpf.job_no_degree_mention,
    jpf.job_health_insurance,
    jpf.job_country,
    jpf.salary_rate,
    jpf.salary_year_avg,
    jpf.salary_hour_avg,
    cd.name AS company_name
FROM data_jobs.job_postings_fact AS jpf
LEFT JOIN data_jobs.company_dim AS cd
    ON jpf.company_id = cd.company_id;

SELECT *
FROM staging.job_postings_flat
LIMIT 20;